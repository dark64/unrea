use proc_macro::{Delimiter, Group, TokenStream, TokenTree};
use std::str::FromStr;

use unrea::{Evasion, Intensity, Target, Unrea};

/// Attribute macro: generate and embed anti-reverse-engineering payloads at compile
/// time alongside the annotated item. See the crate docs for arguments.
#[proc_macro_attribute]
pub fn unrea(attr: TokenStream, item: TokenStream) -> TokenStream {
    let args = match Args::parse(attr) {
        Ok(a) => a,
        Err(e) => return compile_error(&e),
    };

    let item_name = find_item_name(&item);
    let seed = args.seed ^ fnv1a(item_name.as_deref().unwrap_or("item"));

    let mut builder = Unrea::new()
        .seed(seed)
        .intensity(args.intensity)
        .defense(args.defense)
        .with_injection(args.injection)
        .evasion(args.evasion);
    if let Some(claim) = &args.claim {
        builder = builder.claim_benign_analysis(claim.clone());
    }
    builder = match &args.models {
        Some(models) => builder.target_models(models.iter().cloned()),
        None => builder.target_all(),
    };

    let (generated, anchor) = match builder.protection_with_anchor() {
        Ok(pair) => pair,
        Err(e) => return compile_error(&format!("unrea: {e}")),
    };

    let generated_ts = match TokenStream::from_str(&generated) {
        Ok(ts) => ts,
        Err(e) => return compile_error(&format!("unrea: generated code failed to parse: {e}")),
    };

    let item = if args.anchor && !anchor.is_empty() {
        match TokenStream::from_str(&anchor) {
            Ok(anchor_ts) => inject_anchor(item, anchor_ts),
            Err(e) => return compile_error(&format!("unrea: anchor failed to parse: {e}")),
        }
    } else {
        item
    };

    if let Some(dump) = &args.dump {
        let path = if dump.is_empty() {
            format!(
                "target/unrea-dump/{}.rs",
                item_name.as_deref().unwrap_or("item")
            )
        } else {
            dump.clone()
        };
        let contents = format!(
            "// Generated by unrea `#[unrea]`: full expansion of `{}`.\n\n{}\n\n{}\n",
            item_name.as_deref().unwrap_or("item"),
            item,
            generated
        );
        if let Err(e) = write_dump(&path, &contents) {
            return compile_error(&format!("unrea: could not write dump to `{path}`: {e}"));
        }
    }

    let mut out = item;
    out.extend(generated_ts);
    out
}

fn item_is_fn(item: &TokenStream) -> bool {
    item.clone()
        .into_iter()
        .any(|t| matches!(t, TokenTree::Ident(id) if id.to_string() == "fn"))
}

fn inject_anchor(item: TokenStream, anchor: TokenStream) -> TokenStream {
    if !item_is_fn(&item) {
        return item;
    }
    let trees: Vec<TokenTree> = item.into_iter().collect();
    let pos = trees
        .iter()
        .rposition(|t| matches!(t, TokenTree::Group(g) if g.delimiter() == Delimiter::Brace));
    let pos = match pos {
        Some(p) => p,
        None => return trees.into_iter().collect(),
    };

    let mut out = TokenStream::new();
    for (i, t) in trees.into_iter().enumerate() {
        if i == pos {
            if let TokenTree::Group(g) = &t {
                let mut inner = anchor.clone();
                inner.extend(g.stream());
                let mut ng = Group::new(Delimiter::Brace, inner);
                ng.set_span(g.span());
                out.extend(std::iter::once(TokenTree::Group(ng)));
                continue;
            }
        }
        out.extend(std::iter::once(t));
    }
    out
}

fn write_dump(path: &str, contents: &str) -> std::io::Result<()> {
    let p = std::path::Path::new(path);
    if let Some(parent) = p.parent() {
        if !parent.as_os_str().is_empty() {
            std::fs::create_dir_all(parent)?;
        }
    }
    std::fs::write(p, contents)?;
    let _ = std::process::Command::new("rustfmt")
        .args(["--edition", "2021"])
        .arg(p)
        .status();
    Ok(())
}

struct Args {
    models: Option<Vec<String>>,
    claim: Option<String>,
    seed: u64,
    intensity: Intensity,
    evasion: Evasion,
    defense: Target,
    injection: bool,
    anchor: bool,
    dump: Option<String>,
}

impl Args {
    fn parse(attr: TokenStream) -> Result<Args, String> {
        let mut args = Args {
            models: None,
            claim: None,
            seed: 0,
            intensity: Intensity::Medium,
            evasion: Evasion::None,
            defense: Target::Binary,
            injection: true,
            anchor: true,
            dump: None,
        };

        let mut iter = attr.into_iter().peekable();
        while iter.peek().is_some() {
            let key = match iter.next() {
                Some(TokenTree::Ident(id)) => id.to_string(),
                Some(other) => return Err(format!("expected a key identifier, found `{other}`")),
                None => break,
            };

            match iter.next() {
                Some(TokenTree::Punct(p)) if p.as_char() == '=' => {}
                _ => return Err(format!("expected `=` after `{key}`")),
            }

            let value = match iter.next() {
                Some(tt) => tt,
                None => return Err(format!("expected a value after `{key} =`")),
            };

            match key.as_str() {
                "models" => args.models = Some(split_csv(&literal_string(&value)?)),
                "claim" => args.claim = Some(literal_string(&value)?),
                "seed" => {
                    args.seed = match &value {
                        TokenTree::Ident(id)
                            if matches!(id.to_string().as_str(), "random" | "auto") =>
                        {
                            entropy_seed()
                        }
                        _ => literal_int(&value)?,
                    };
                }
                "intensity" => {
                    args.intensity = match ident_or_string(&value)?.as_str() {
                        "low" => Intensity::Low,
                        "medium" => Intensity::Medium,
                        "high" => Intensity::High,
                        other => return Err(format!("unknown intensity `{other}`")),
                    }
                }
                "evasion" => {
                    args.evasion = match ident_or_string(&value)?.as_str() {
                        "none" => Evasion::None,
                        "nonprinting" => Evasion::NonPrinting,
                        "nullsplit" => Evasion::NullSplit,
                        other => return Err(format!("unknown evasion `{other}`")),
                    }
                }
                "defense" => {
                    args.defense = match ident_or_string(&value)?.as_str() {
                        "binary" => Target::Binary,
                        "source" => Target::Source,
                        other => return Err(format!("unknown defense `{other}`")),
                    }
                }
                "injection" => {
                    args.injection = match ident_or_string(&value)?.as_str() {
                        "true" => true,
                        "false" => false,
                        other => {
                            return Err(format!(
                                "expected true/false for injection, found `{other}`"
                            ))
                        }
                    }
                }
                "anchor" => {
                    args.anchor = match ident_or_string(&value)?.as_str() {
                        "true" => true,
                        "false" => false,
                        other => {
                            return Err(format!("expected true/false for anchor, found `{other}`"))
                        }
                    }
                }
                "dump" => {
                    args.dump = match &value {
                        TokenTree::Ident(id) if id.to_string() == "true" => Some(String::new()),
                        TokenTree::Ident(id) if id.to_string() == "false" => None,
                        _ => Some(literal_string(&value)?),
                    };
                }
                other => return Err(format!("unknown argument `{other}`")),
            }

            // optional trailing comma
            if let Some(TokenTree::Punct(p)) = iter.peek() {
                if p.as_char() == ',' {
                    iter.next();
                }
            }
        }
        Ok(args)
    }
}

fn literal_string(tt: &TokenTree) -> Result<String, String> {
    match tt {
        TokenTree::Literal(lit) => {
            let s = lit.to_string();
            let trimmed = s
                .strip_prefix('"')
                .and_then(|s| s.strip_suffix('"'))
                .ok_or_else(|| format!("expected a string literal, found `{s}`"))?;
            Ok(trimmed.to_string())
        }
        other => Err(format!("expected a string literal, found `{other}`")),
    }
}

fn literal_int(tt: &TokenTree) -> Result<u64, String> {
    match tt {
        TokenTree::Literal(lit) => {
            let s = lit.to_string();
            let cleaned: String = s.chars().filter(|c| *c != '_').collect();
            u64::from_str(&cleaned).map_err(|_| format!("expected an integer, found `{s}`"))
        }
        other => Err(format!("expected an integer, found `{other}`")),
    }
}

fn ident_or_string(tt: &TokenTree) -> Result<String, String> {
    match tt {
        TokenTree::Ident(id) => Ok(id.to_string()),
        TokenTree::Literal(_) => literal_string(tt),
        other => Err(format!("expected an identifier or string, found `{other}`")),
    }
}

fn split_csv(s: &str) -> Vec<String> {
    s.split(',')
        .map(|p| p.trim().to_string())
        .filter(|p| !p.is_empty())
        .collect()
}

fn find_item_name(item: &TokenStream) -> Option<String> {
    let mut prev_kw = false;
    for tt in item.clone() {
        match tt {
            TokenTree::Ident(id) => {
                let s = id.to_string();
                if prev_kw {
                    return Some(s);
                }
                prev_kw = matches!(
                    s.as_str(),
                    "fn" | "struct" | "enum" | "mod" | "static" | "const" | "trait" | "impl"
                );
            }
            _ => prev_kw = false,
        }
    }
    None
}

fn entropy_seed() -> u64 {
    use std::time::{SystemTime, UNIX_EPOCH};
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(0);
    let pid = std::process::id() as u64;
    let mut z = nanos ^ pid.wrapping_mul(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

fn fnv1a(s: &str) -> u64 {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for b in s.bytes() {
        hash ^= b as u64;
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    hash
}

fn compile_error(msg: &str) -> TokenStream {
    let escaped = msg.replace('\\', "\\\\").replace('"', "\\\"");
    TokenStream::from_str(&format!("::core::compile_error!(\"{escaped}\");")).unwrap()
}
